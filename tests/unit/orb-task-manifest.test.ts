// Orb task bridge — the static action facts taskState/listEnabledTasks read at
// request time (src/modules/ai/tasks/manifest.ts), so the tenant layout never
// loads the action registry. This test keeps the file equal to the registry.
// Regenerate after adding or changing an action: UPDATE_ORB_MANIFEST=1 pnpm test tests/unit/orb-task-manifest.test.ts
import fs from "node:fs";
import path from "node:path";
import { describe, expect, it, vi } from "vitest";
import { getActionMeta } from "@/lib/actions/registry";
import { ACTION_RISK } from "@/modules/agents/catalog";
import { actionJsonSchema, deriveMode, deriveRisk } from "@/modules/ai/tasks/derive";
import { ACTION_FACTS } from "@/modules/ai/tasks/manifest";

vi.mock("@/lib/supabase/server", () => import("../helpers/server-client-mock"));

const FILE = path.join(process.cwd(), "src/modules/ai/tasks/manifest.ts");
const RISKS = new Set(["low_risk_reversible", "user_confirmed", "human_approved"]);

async function expected(): Promise<Record<string, readonly [string | null, string, string, string]>> {
  await import("@/app/api/v1/actions/all-actions");
  const out: Record<string, readonly [string | null, string, string, string]> = {};
  for (const [name, meta] of [...getActionMeta()].sort(([a], [b]) => a.localeCompare(b))) {
    const schema = actionJsonSchema(meta);
    const seeded = ACTION_RISK[name];
    const risk = seeded && RISKS.has(seeded) ? seeded : deriveRisk(name, schema);
    out[name] = [meta.permission, meta.module ?? "core", deriveMode(name, meta.module, schema), risk];
  }
  return out;
}

function render(facts: Record<string, readonly [string | null, string, string, string]>): string {
  const rows = Object.entries(facts).map(([name, [p, m, mode, risk]]) => `  ${JSON.stringify(name)}: [${JSON.stringify(p)}, ${JSON.stringify(m)}, ${JSON.stringify(mode)}, ${JSON.stringify(risk)}],`);
  return [
    "// GENERATED by tests/unit/orb-task-manifest.test.ts — do not edit by hand.",
    "// Regenerate: UPDATE_ORB_MANIFEST=1 pnpm test tests/unit/orb-task-manifest.test.ts",
    "// Per registered action: [static permission (null = depends on input), module, derived mode, derived risk].",
    "// taskState reads these instead of loading the action registry on every page (catalog rows still override mode and risk).",
    'import type { Permission } from "@/lib/auth/permissions";',
    'import type { ModuleKey } from "@/lib/modules/catalog";',
    'import type { TaskMode, TaskRisk } from "./types";',
    "",
    "export const ACTION_FACTS: Readonly<Record<string, readonly [Permission | null, ModuleKey, TaskMode, TaskRisk]>> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}

describe("orb task manifest", () => {
  it("equals the facts derived from the live action registry", async () => {
    const facts = await expected();
    if (process.env.UPDATE_ORB_MANIFEST === "1") fs.writeFileSync(FILE, render(facts));
    expect(ACTION_FACTS).toEqual(facts);
  });
});
