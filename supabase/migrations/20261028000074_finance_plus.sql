-- ---------------------------------------------------------------------------
-- app.void_payment(...) — rule 5 (new row, never an edit); same lock as
-- app.record_payment (0008/0021) on the invoice, no deadlock (payment is
-- read without a lock — it is immutable and never written again here).
-- Order of checks is fixed by the M12-T4 ruling: not_found (payment) →
-- not_found (invoice) → idempotent fast path → already-reversed conflict →
-- cancelled invoice → kind/cheque_bounce/reason validation.
-- ---------------------------------------------------------------------------

create function app.void_payment(
  p_payment_id uuid,
  p_kind text,
  p_reason text,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_payment public.payments;
  v_invoice public.invoices;
  v_receipt public.receipts;
  v_institution_id uuid;
  v_existing_reversal_id uuid;
  v_existing_invoice_id uuid;
  v_existing_payment_id uuid;
  v_already_reversed_id uuid;
  v_reversal_id uuid;
  v_timezone text;
  v_today date;
  v_account text;
  v_new_paid_total numeric(12, 2);
  v_new_status text;
  v_snapshot jsonb;
begin
  select * into v_payment from public.payments where id = p_payment_id;
  if v_payment.id is null then
    raise exception 'code:not_found' using detail = 'payment not found';
  end if;

  v_institution_id := v_payment.institution_id;

  select * into v_invoice from public.invoices where id = v_payment.invoice_id for update;
  if v_invoice.id is null then
    raise exception 'code:not_found' using detail = 'invoice not found';
  end if;

  -- Idempotent fast path: a replay of an already-reversed request returns
  -- the existing reversal without touching the invoice or ledger again.
  -- The key must belong to THIS payment: reused for another payment ->
  -- conflict (never report the other payment's reversal as this one's).
  select id, invoice_id, payment_id into v_existing_reversal_id, v_existing_invoice_id, v_existing_payment_id
  from public.payment_reversals
  where institution_id = v_institution_id and idempotency_key = p_idempotency_key;

  if v_existing_reversal_id is not null and v_existing_payment_id <> p_payment_id then
    raise exception 'code:conflict' using detail = 'idempotency key already used for another payment';
  end if;

  if v_existing_reversal_id is not null then
    select status, paid_total into v_new_status, v_new_paid_total
    from public.invoices where id = v_existing_invoice_id;
    return jsonb_build_object(
      'reversal_id', v_existing_reversal_id, 'invoice_id', v_existing_invoice_id,
      'invoice_status', v_new_status, 'paid_total', v_new_paid_total
    );
  end if;

  select id into v_already_reversed_id from public.payment_reversals where payment_id = p_payment_id;
  if v_already_reversed_id is not null then
    raise exception 'code:conflict' using detail = 'payment already reversed';
  end if;

  if v_invoice.status = 'cancelled' then
    raise exception 'code:invalid_state' using detail = 'invoice is cancelled';
  end if;

  if p_kind not in ('void', 'refund', 'cheque_bounce') then
    raise exception 'code:validation_failed' using detail = 'invalid reversal kind';
  end if;

  if p_kind = 'cheque_bounce' and v_payment.mode <> 'cheque' then
    raise exception 'code:validation_failed' using detail = 'cheque_bounce requires a cheque payment';
  end if;

  if p_reason is null or char_length(trim(p_reason)) < 5 or char_length(trim(p_reason)) > 500 then
    raise exception 'code:validation_failed' using detail = 'reason must be 5-500 characters';
  end if;

  select * into v_receipt from public.receipts where payment_id = p_payment_id;
  if v_receipt.id is null then
    raise exception 'code:invalid_state' using detail = 'payment has no receipt';
  end if;

  select coalesce(i.settings -> 'locale' ->> 'timezone', 'Asia/Kolkata') into v_timezone
  from public.institutions i where i.id = v_institution_id;
  v_today := (now() at time zone v_timezone)::date;

  -- Snapshot = the receipt's own snapshot plus a `reversal` key — the
  -- receipt row itself stays untouched (immutable); this is the "receipt
  -- marked void" view.
  v_snapshot := v_receipt.snapshot || jsonb_build_object(
    'reversal', jsonb_build_object(
      'kind', p_kind, 'reason', p_reason, 'amount', v_payment.amount,
      'receipt_no', v_receipt.receipt_no, 'reversed_at', now()
    )
  );

  insert into public.payment_reversals (institution_id, payment_id, invoice_id, kind, amount, reason, snapshot, idempotency_key, reversed_by)
  values (v_institution_id, p_payment_id, v_invoice.id, p_kind, v_payment.amount, p_reason, v_snapshot, p_idempotency_key, app.current_user_id())
  on conflict (institution_id, idempotency_key) do nothing
  returning id into v_reversal_id;

  if v_reversal_id is null then
    -- Lost the race to a concurrent call with the same key: return the winner's result.
    select id, payment_id into v_reversal_id, v_existing_payment_id from public.payment_reversals
    where institution_id = v_institution_id and idempotency_key = p_idempotency_key;
    if v_existing_payment_id <> p_payment_id then
      raise exception 'code:conflict' using detail = 'idempotency key already used for another payment';
    end if;
    select status, paid_total into v_new_status, v_new_paid_total from public.invoices where id = v_invoice.id;
    return jsonb_build_object(
      'reversal_id', v_reversal_id, 'invoice_id', v_invoice.id,
      'invoice_status', v_new_status, 'paid_total', v_new_paid_total
    );
  end if;

  -- Same ledger shape as record_payment, reversed: Dr fees_receivable
  -- (the debt is owed again) / Cr cash|bank (the money went back or the
  -- cheque never cleared) — all three kinds post the same entries (06
  -- ruling: refund = money back + fee due again; waiving the fee is
  -- invoice cancellation, not this function).
  v_account := case when v_payment.mode = 'cash' then 'cash' else 'bank' end;

  insert into public.ledger_entries (institution_id, payment_id, invoice_id, account, debit, credit, entry_date, memo)
  values (v_institution_id, p_payment_id, v_invoice.id, 'fees_receivable', v_payment.amount, 0, v_today, p_kind || ' receipt ' || v_receipt.receipt_no);

  insert into public.ledger_entries (institution_id, payment_id, invoice_id, account, debit, credit, entry_date, memo)
  values (v_institution_id, p_payment_id, v_invoice.id, v_account, 0, v_payment.amount, v_today, p_kind || ' receipt ' || v_receipt.receipt_no);

  v_new_paid_total := v_invoice.paid_total - v_payment.amount;
  v_new_status := case when v_new_paid_total <= 0 then 'issued' else 'part_paid' end;

  update public.invoices set paid_total = v_new_paid_total, status = v_new_status where id = v_invoice.id;

  -- Never audit `reason` (free text, 07 §4 lesson 10).
  perform app.audit(
    v_institution_id,
    app.current_user_id(),
    'finance.payment.voided',
    'payment',
    p_payment_id,
    jsonb_build_object('paid_total', v_invoice.paid_total, 'status', v_invoice.status),
    jsonb_build_object('paid_total', v_new_paid_total, 'status', v_new_status),
    jsonb_build_object('kind', p_kind, 'amount', v_payment.amount, 'receipt_no', v_receipt.receipt_no)
  );

  return jsonb_build_object(
    'reversal_id', v_reversal_id, 'invoice_id', v_invoice.id,
    'invoice_status', v_new_status, 'paid_total', v_new_paid_total
  );
end;
$$;

revoke execute on function app.void_payment(uuid, text, text, text) from public, anon, authenticated;

-- public.void_payment — role check lives here (app is never
-- PostgREST-exposed), `authenticated` only (no gateway/service-role caller
-- for this one — no Razorpay refund API in scope, so there is no automated
-- caller to trust unchecked).
--
-- Deviation from 0008's single-check wrapper pattern (recorded here and in
-- the completion report): the M12-T4 ruling requires a caller from a
-- DIFFERENT institution to get not_found (never reveal that the payment
-- exists), while a same-institution caller who simply lacks the void role
-- gets forbidden. 0008's `v_institution_id is null or not has_role(...) =>
-- forbidden` cannot distinguish those two cases (no membership and wrong
-- role both evaluate `has_role` to false) — membership is checked first
-- here instead, before the role check.
create function public.void_payment(
  p_payment_id uuid,
  p_kind text,
  p_reason text,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_institution_id uuid;
begin
  if app.current_user_id() is null then
    raise exception 'code:unauthenticated' using detail = 'sign-in required';
  end if;

  select institution_id into v_institution_id from public.payments where id = p_payment_id;

  if v_institution_id is null or not app.is_member(v_institution_id) then
    raise exception 'code:not_found' using detail = 'payment not found';
  end if;

  if not app.has_role(v_institution_id, app.finance_void_roles()) then
    raise exception 'code:forbidden' using detail = 'caller does not hold a finance.payment.void role for this institution';
  end if;

  return app.void_payment(p_payment_id, p_kind, p_reason, p_idempotency_key);
end;
$$;

revoke execute on function public.void_payment(uuid, text, text, text) from public, anon;
grant execute on function public.void_payment(uuid, text, text, text) to authenticated;

-- ---------------------------------------------------------------------------
-- public.enqueue_fee_reminders(...) — same shape as public.enqueue_term_invoices
-- (0017): single public.* definer (no trusted internal caller needs an
-- unchecked app.* twin), role check directly here, payload built entirely
-- from a row already proven to belong to this institution.
-- ---------------------------------------------------------------------------

create function public.enqueue_fee_reminders(p_institution_id uuid, p_term_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_term public.terms;
  v_timezone text;
  v_as_of date;
  v_payload jsonb;
  v_key text;
  v_job_id uuid;
begin
  if app.current_user_id() is null then
    raise exception 'code:unauthenticated' using detail = 'sign-in required';
  end if;

  if not app.has_role(p_institution_id, app.finance_write_roles()) then
    raise exception 'code:forbidden' using detail = 'caller does not hold a finance.reminder.send role for this institution';
  end if;

  select * into v_term from public.terms where id = p_term_id and institution_id = p_institution_id;
  if v_term.id is null then
    raise exception 'code:not_found' using detail = 'term not found for this institution';
  end if;

  select coalesce(i.settings -> 'locale' ->> 'timezone', 'Asia/Kolkata') into v_timezone
  from public.institutions i where i.id = p_institution_id;
  v_as_of := (now() at time zone v_timezone)::date;

  v_payload := jsonb_build_object('term_id', p_term_id, 'as_of', v_as_of);
  v_key := 'fee_reminders:' || p_term_id::text || ':' || v_as_of::text;

  v_job_id := app.enqueue_job(p_institution_id, 'finance.fee_reminder', v_payload, v_key);

  perform app.audit(
    p_institution_id,
    app.current_user_id(),
    'finance.reminders.enqueued',
    'term',
    p_term_id,
    null,
    v_payload,
    jsonb_build_object('jobId', v_job_id, 'key', v_key)
  );

  return jsonb_build_object('jobId', v_job_id);
end;
$$;

revoke execute on function public.enqueue_fee_reminders(uuid, uuid) from public, anon;
grant execute on function public.enqueue_fee_reminders(uuid, uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- public.finance_collection_report(...) — `security invoker` like 0082's
-- ledger_totals/term_collection_totals: no role check inside, the
-- underlying tables' own RLS (invoices/payments/ledger_entries/
-- payment_reversals/fee_assignments/fee_structures/grades/terms, all
-- finance_roles()-or-narrower) already scopes every row a caller can see.
-- A caller outside those roles gets 0 rows summed to 0, not an error.
-- ---------------------------------------------------------------------------

create function public.finance_collection_report(
  p_institution_id uuid,
  p_academic_year_id uuid,
  p_term_id uuid default null,
  p_group_by text default null
)
returns table (
  group_key text,
  group_label text,
  sort_order int,
  invoice_count bigint,
  payment_count bigint,
  billed numeric,
  collected numeric,
  reversed numeric,
  outstanding numeric
)
language plpgsql
stable
security invoker
set search_path = ''
as $$
begin
  if p_group_by is null or p_group_by not in ('term', 'grade', 'mode') then
    raise exception 'code:validation_failed' using detail = 'group_by must be term, grade, or mode';
  end if;

  if p_group_by = 'term' then
    return query
    with scoped as (
      select i.id, i.term_id, i.total, i.paid_total
      from public.invoices i
      where i.institution_id = p_institution_id
        and i.academic_year_id = p_academic_year_id
        and i.status <> 'cancelled'
        and (p_term_id is null or i.term_id = p_term_id)
    ),
    inv_agg as (
      select s.term_id as key_id, count(*) as invoice_count, coalesce(sum(s.total), 0) as billed, coalesce(sum(s.paid_total), 0) as collected
      from scoped s
      group by s.term_id
    ),
    pay_agg as (
      select s.term_id as key_id,
             count(p.id) filter (where pr.id is null) as payment_count,
             coalesce(sum(pr.amount), 0) as reversed
      from scoped s
      join public.payments p on p.invoice_id = s.id
      left join public.payment_reversals pr on pr.payment_id = p.id
      group by s.term_id
    )
    select
      t.id::text,
      t.name,
      t.sequence,
      ia.invoice_count,
      coalesce(pa.payment_count, 0),
      ia.billed,
      ia.collected,
      coalesce(pa.reversed, 0),
      ia.billed - ia.collected
    from public.terms t
    join inv_agg ia on ia.key_id = t.id
    left join pay_agg pa on pa.key_id = t.id
    order by t.sequence;
    return;

  elsif p_group_by = 'grade' then
    return query
    with scoped as (
      select i.id, i.student_id, i.academic_year_id, i.total, i.paid_total
      from public.invoices i
      where i.institution_id = p_institution_id
        and i.academic_year_id = p_academic_year_id
        and i.status <> 'cancelled'
        and (p_term_id is null or i.term_id = p_term_id)
    ),
    scoped_grade as (
      select s.id, s.total, s.paid_total, fs.grade_id
      from scoped s
      join public.fee_assignments fa on fa.student_id = s.student_id and fa.academic_year_id = s.academic_year_id
      join public.fee_structures fs on fs.id = fa.fee_structure_id
    ),
    inv_agg as (
      select sg.grade_id as key_id, count(*) as invoice_count, coalesce(sum(sg.total), 0) as billed, coalesce(sum(sg.paid_total), 0) as collected
      from scoped_grade sg
      group by sg.grade_id
    ),
    pay_agg as (
      select sg.grade_id as key_id,
             count(p.id) filter (where pr.id is null) as payment_count,
             coalesce(sum(pr.amount), 0) as reversed
      from scoped_grade sg
      join public.payments p on p.invoice_id = sg.id
      left join public.payment_reversals pr on pr.payment_id = p.id
      group by sg.grade_id
    )
    select
      g.id::text,
      g.display_name,
      g.sort_key,
      ia.invoice_count,
      coalesce(pa.payment_count, 0),
      ia.billed,
      ia.collected,
      coalesce(pa.reversed, 0),
      ia.billed - ia.collected
    from public.grades g
    join inv_agg ia on ia.key_id = g.id
    left join pay_agg pa on pa.key_id = g.id
    order by g.sort_key;
    return;

  else
    return query
    with scoped as (
      select i.id
      from public.invoices i
      where i.institution_id = p_institution_id
        and i.academic_year_id = p_academic_year_id
        and i.status <> 'cancelled'
        and (p_term_id is null or i.term_id = p_term_id)
    )
    select
      p.mode,
      p.mode,
      0,
      count(distinct p.invoice_id),
      count(p.id),
      null::numeric,
      coalesce(sum(p.amount), 0) - coalesce(sum(pr.amount), 0),
      coalesce(sum(pr.amount), 0),
      null::numeric
    from scoped s
    join public.payments p on p.invoice_id = s.id
    left join public.payment_reversals pr on pr.payment_id = p.id
    group by p.mode
    order by p.mode;
    return;
  end if;
end;
$$;

revoke execute on function public.finance_collection_report(uuid, uuid, uuid, text) from public, anon;
grant execute on function public.finance_collection_report(uuid, uuid, uuid, text) to authenticated;
