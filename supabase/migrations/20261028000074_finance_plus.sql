-- ---------------------------------------------------------------------------
-- payment_reversals (rule 5: a reversal is a new row, never an edit of
-- payments/receipts/invoices). Immutable (block_mutation) with the usual
-- demo-reset bypass.
-- ---------------------------------------------------------------------------

create table public.payment_reversals (
  id uuid primary key default gen_random_uuid(),
  institution_id uuid not null references public.institutions (id),
  payment_id uuid not null unique references public.payments (id),
  invoice_id uuid not null references public.invoices (id),
  kind text not null check (kind in ('void', 'refund', 'cheque_bounce')),
  amount numeric(12, 2) not null check (amount > 0),
  reason text not null check (char_length(reason) between 5 and 500),
  snapshot jsonb not null,
  idempotency_key text not null,
  reversed_by uuid references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (institution_id, idempotency_key)
);

create index payment_reversals_institution_id_idx on public.payment_reversals (institution_id);
create index payment_reversals_invoice_id_idx on public.payment_reversals (invoice_id);

create trigger set_updated_at
before update on public.payment_reversals
for each row execute function app.set_updated_at();

create trigger block_mutation
before update or delete on public.payment_reversals
for each row execute function app.block_mutation();

alter table public.payment_reversals enable row level security;

-- SELECT only (no insert/update/delete policy — definer-only writes,
-- lesson 3). Mirrors receipts_select (0020): finance_roles() full read, plus
-- the invoice's own guardian/student scope — the reversal `reason` is
-- therefore payer-visible by design (it prints on the void receipt).
create policy payment_reversals_select on public.payment_reversals
  for select to authenticated
  using (
    institution_id = any((select app.my_institution_ids(app.finance_roles())))
    or exists (
      select 1 from public.invoices i
      where i.id = payment_reversals.invoice_id
        and i.institution_id = payment_reversals.institution_id
        and i.student_id = any((select app.my_student_ids()))
    )
  );

